#!/usr/bin/env python3
"""Regenerate Canteen/ITA/S117_1/Cpi.lean from data/statcan-cpi-41690973.json.

To add a month: fetch the series again (POST to the Statistics Canada WDS endpoint named in the JSON,
body [{"vectorId":41690973,"latestN":N}]), update the JSON, and run this script.
"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
d = json.loads((root / "data/statcan-cpi-41690973.json").read_text())
months = sorted(d["monthly"])
first = months[0]
vals = [round(d["monthly"][m] * 10) for m in months]
y0, m0 = map(int, first.split("-"))
lines = ["/- Generated by scripts/cpi.py from data/statcan-cpi-41690973.json. Do not edit by hand. -/", "",
         "namespace Canteen.ITA.Indexation", "",
         f"/-- {d['source']}. Retrieved {d['retrieved']}. -/",
         f"def cpiFirstYear : Nat := {y0}", f"def cpiFirstMonth : Nat := {m0}", "",
         "/-- Monthly values, in tenths of an index point, from the first month on. -/",
         "def cpiTenths : Array Nat := #["]
for i in range(0, len(vals), 12):
    lines.append("  " + ", ".join(map(str, vals[i:i+12])) + ("," if i + 12 < len(vals) else ""))
lines += ["]", "", "end Canteen.ITA.Indexation", ""]
(root / "Canteen/ITA/S117_1/Cpi.lean").write_text("\n".join(lines))
print(f"{len(vals)} months, {first} to {months[-1]}")
